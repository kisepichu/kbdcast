#!/usr/bin/env bun
// Generates src/vt/width_table.emel and test/vt_golden.emel from avt 0.18.0 (the terminal emulator of agg 1.9.0).
// usage: mise exec -- bun tools/gen-vt-golden.ts [seed count]
// With a seed and a count, it writes test/vt_golden.emel from other random cases, to explore. Run it again without
// them afterwards, to put the table back.
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const HARNESS = join(ROOT, "tools", "avt-golden", "Cargo.toml");
const WIDTH_OUT = join(ROOT, "src", "vt", "width_table.emel");
const CASES_OUT = join(ROOT, "test", "vt_golden.emel");

function harness(args: string[]): string[] {
  const command = ["cargo", "run", "--release", "--quiet", "--locked", "--manifest-path", HARNESS, "--", ...args];
  const run = Bun.spawnSync(command, { stdout: "pipe", stderr: "inherit" });
  if (run.exitCode !== 0) throw new Error(`avt-golden ${args.join(" ")} が失敗した`);
  return run.stdout.toString().trimEnd().split("\n");
}

// Code points written as `1b.5b.41` as an Emela string literal. Printable ASCII stays as it is, except `"`, `\` and
// `#` (which could start an interpolation); every other code point is a `\u{...}` escape.
function literal(codes: string): string {
  const chars = codes === "" ? [] : codes.split(".").map((h) => Number.parseInt(h, 16));
  const body = chars
    .map((c) => (c >= 0x20 && c <= 0x7e && c !== 0x22 && c !== 0x5c && c !== 0x23 ? String.fromCharCode(c) : `\\u{${c.toString(16)}}`))
    .join("");
  return `"${body}"`;
}

function fmt(path: string) {
  const run = Bun.spawnSync(["emela", "fmt", path], { stdout: "inherit", stderr: "inherit" });
  if (run.exitCode !== 0) throw new Error(`emela fmt が失敗した: ${path}`);
}

const explore = process.argv.slice(2);
if (explore.length !== 0 && explore.length !== 2) throw new Error("使い方: mise exec -- bun tools/gen-vt-golden.ts [seed count]");

if (explore.length === 0) {
  const ranges = harness(["width"]).map((line) => line.split("\t").map((h) => `0x${h}`));
  writeFileSync(
    WIDTH_OUT,
    `# Generated by tools/gen-vt-golden.ts from unicode-width 0.1.14 (tools/avt-golden). Do not edit.

## The first code point of each range of code points that avt 0.18.0 draws two columns wide (above U+007E, and
## two columns wide for unicode-width 0.1.14), in increasing order.
pub const WIDE_FIRST: List[Int] = [
${ranges.map((r) => `  ${r[0]},`).join("\n")}
]

## The last code point of each range in WIDE_FIRST, at the same position.
pub const WIDE_LAST: List[Int] = [
${ranges.map((r) => `  ${r[1]},`).join("\n")}
]
`,
  );
  fmt(WIDTH_OUT);
  console.log(`wrote ${WIDTH_OUT}: ${ranges.length} ranges`);
}

const cases = harness(["cases", ...explore]).map((line) => {
  const [name, cols, rows, input, snapshot] = line.split("\t");
  return `  ("${name}", ${cols}, ${rows}, ${literal(input)}, ${literal(snapshot)}),`;
});
writeFileSync(
  CASES_OUT,
  `# Generated by tools/gen-vt-golden.ts from avt 0.18.0 (tools/avt-golden). Do not edit.

## What avt makes of each input: the name of the case, the columns and rows of the screen, the input, and the
## snapshot of the screen after it. The format of the snapshot is in tools/avt-golden/src/main.rs.
pub const CASES: List[(String, Int, Int, String, String)] = [
${cases.join("\n")}
]
`,
);
fmt(CASES_OUT);
console.log(`wrote ${CASES_OUT}: ${cases.length} cases`);
